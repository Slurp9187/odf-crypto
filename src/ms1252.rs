fn direct(c: u16) -> Option<u8> {
    match c {
        0..=0x7F | 0xA0..=0xFF => Some(c as u8),
        _ => TO_CHAR_EX
            .binary_search_by_key(&c, |&(u, _)| u)
            .ok()
            .and_then(|i| TO_CHAR_EX.get(i))
            .map(|&(_, b)| b),
    }
}

fn byte_for(c: char) -> u8 {
    // Outside the BMP: a surrogate pair upstream, which converts to one `?`.
    let Ok(c) = u16::try_from(u32::from(c)) else {
        return b'?';
    };
    if let Some(b) = direct(c) {
        return b;
    }
    if let Some(&(_, b)) = REPLACE
        .binary_search_by_key(&c, |&(u, _)| u)
        .ok()
        .and_then(|i| REPLACE.get(i))
    {
        return b;
    }
    match c {
        0xF100..=0xF1FF => (c - 0xF100) as u8,
        _ => b'?',
    }
}

/// `password` as MS-1252 bytes, exactly one byte per `char`.
///
/// Wrapped from the first byte: this is the password itself in another
/// encoding, so it gets the same zeroize-on-drop as the digest made from it.
pub(crate) fn encode(password: &str) -> PasswordBytes {
    let n = password.chars().count();
    PasswordBytes::new_with(n, |slot| {
        for (dst, c) in slot.iter_mut().zip(password.chars()) {
            *dst = byte_for(c);
        }
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use secure_gate::RevealSecret;

    fn enc(s: &str) -> Vec<u8> {
        encode(s).with_secret(|b| b.to_vec())
    }

    #[test]
    fn tables_are_sorted_so_binary_search_finds_every_row() {
        assert!(TO_CHAR_EX.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(REPLACE.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(!REPLACE.is_empty());
    }

    #[test]
    fn each_conversion_step_is_reached() {
        // 1. direct: ASCII, Latin-1 upper half, and the extension table.
        assert_eq!(enc("aä€"), [b'a', 0xE4, 0x80]);
        // C1 controls are not in LibreOffice's reverse table.
        assert_eq!(enc("\u{0081}\u{0090}"), b"??");
        // 2. similar-character fallback: EN QUAD becomes a space.
        assert_eq!(enc("\u{2000}"), b" ");
        // 3. the private-use byte range.
        assert_eq!(enc("\u{F1E4}"), [0xE4]);
        // 4. undefined, and one `?` per non-BMP character, not two.
        assert_eq!(enc("\u{0100}\u{1F600}"), b"??");
    }
}
