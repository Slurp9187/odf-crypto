//! Password bytes as LibreOffice's MS-1252 encoder produces them, for the
//! last rung of the legacy SHA-1 read ladder (see [`crate::kdf::LegacyStartKey`]).
//!
//! **Not WHATWG `windows-1252`, and must not be replaced with `encoding_rs`.**
//! The caller is `OStorageHelper::CreatePackageEncryptionData`
//! (`comphelper/source/misc/storagehelper.cxx`), which converts with
//! `OUStringToOString(.., RTL_TEXTENCODING_MS_1252)` and so with
//! `OUSTRING_TO_OSTRING_CVTFLAGS` (`include/rtl/string.h`). That conversion,
//! `convertUnicodeToChar` in `sal/textenc/convertsimple.cxx`, never fails:
//!
//! 1. ASCII, U+00A0..=U+00FF, and the 27 characters of `aImplMS1252ToCharTabEx`
//!    (`sal/textenc/textenc.cxx`) map directly. U+0080..=U+009F do **not** --
//!    LibreOffice's table leaves 0x81/0x8D/0x8F/0x90/0x9D unmapped, and the C1
//!    controls are not in the reverse table at all.
//! 2. Otherwise `UNDEFINED_REPLACE` retries once through `aImplRepCharTab`, a
//!    "similar character" table (U+2002 EN SPACE becomes a space). Resolved here
//!    to the rows that land on a byte, by `tools/gen_ms1252.py`.
//! 3. Otherwise `PRIVATE_MAPTO0` maps U+F100..=U+F1FF to its low byte
//!    (`handleUndefinedUnicodeToTextChar`, `RTL_TEXTCVT_BYTE_PRIVATE_START`).
//! 4. Otherwise `?`. A non-BMP character is a UTF-16 surrogate pair upstream,
//!    and the pair together becomes **one** `?`.
//!
//! WHATWG's encoder emits `&#NNNN;` for step 4 and maps the C1 controls, so it
//! would produce a different start key for any password that reaches either.

